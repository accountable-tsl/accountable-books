export function countOpenTasksByClient(
  items: FirmTaskQueueItem[],
): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const t of items) {
    counts[t.clientCompanyId] = (counts[t.clientCompanyId] ?? 0) + 1;
  }
  return counts;
}
