import type {
  GetJournalResponse,
  JournalDetailEntry,
  JournalListCursorResponse,
  JournalListRow,
} from '@accountable-books/contracts/schema';
import { createId } from '@/shared/utils/id-utils';

const mockId = () => createId({ prefix: 'mock-' });

const pad4 = (n: number) => String(n).padStart(4, '0');

const toYMD = (d: Date) => d.toISOString().slice(0, 10);

type MockData = {
  list: JournalListRow[];
  detailsById: Map<string, GetJournalResponse>;
};

export function generateMockJournals({
  companyId,
  currencyCode = 'USD',
  count = 80,
}: {
  companyId: string;
  currencyCode?: string;
  count?: number;
}): MockData {
  const now = new Date();
  const reportingCurrencyId = mockId();

  let seq = 42;
  const list: JournalListRow[] = [];
  const detailsById = new Map<string, GetJournalResponse>();

  const contacts = [
    { id: mockId(), name: 'Acme Properties LLC' },
    { id: mockId(), name: 'Nimbus Payroll Services' },
    { id: mockId(), name: 'Contoso Consulting' },
  ];

  const coaPairs = [
    {
      debit: { code: '6100', name: 'Office Expenses' },
      credit: { code: '2000', name: 'Accrued Liabilities' },
    },
    {
      debit: { code: '7000', name: 'Payroll Expense' },
      credit: { code: '2100', name: 'Payroll Payable' },
    },
    {
      debit: { code: '8000', name: 'Depreciation Expense' },
      credit: { code: '1600', name: 'Accumulated Depreciation' },
    },
    {
      debit: { code: '1100', name: 'Cash' },
      credit: { code: '6500', name: 'Bank Fees' },
    },
  ];

  for (let i = 0; i < count; i += 1) {
    const id = mockId();
    const daysAgo = Math.floor(Math.random() * 120);
    const date = new Date(now);
    date.setDate(now.getDate() - daysAgo);

    const yyyy = date.getUTCFullYear();
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const yyyymm = `${yyyy}${mm}`;

    const statusRoll = Math.random();
    const status =
      statusRoll < 0.65 ? 'posted' : statusRoll < 0.9 ? 'draft' : 'voided';

    const generatedFromTemplate = Math.random() < 0.14 ? mockId() : null;

    const total = Math.round((50 + Math.random() * 9500) * 100) / 100;
    const totalStr = total.toFixed(2);

    const isFx = Math.random() < 0.12;
    const fxCurrencyCode = isFx ? (Math.random() < 0.5 ? 'EUR' : 'GBP') : null;
    const effectiveCurrencyCode = fxCurrencyCode ?? currencyCode;
    const exchangeRate = isFx ? (0.85 + Math.random() * 0.45).toFixed(6) : '1';

    const reference =
      status === 'draft' && Math.random() < 0.35
        ? null
        : `JE-${yyyymm}-${pad4(seq++)}`;

    const titlePool = [
      'Rent accrual',
      'Depreciation',
      'Payroll accrual',
      'Intercompany adjustment',
      'FX revaluation',
      'Prepaid expense amortization',
      'Revenue recognition',
      'Bank fees reclass',
    ];
    const title = titlePool[i % titlePool.length]!;

    const createdAt = new Date(date);
    createdAt.setUTCHours(12, 0, 0, 0);

    const contact =
      Math.random() < 0.35 ? contacts[i % contacts.length]! : null;

    const autoReversalDate =
      status === 'posted' && Math.random() < 0.12
        ? (() => {
            const d = new Date(date);
            d.setUTCDate(d.getUTCDate() + (7 + Math.floor(Math.random() * 21)));
            return toYMD(d);
          })()
        : null;

    const journalRow: JournalListRow = {
      id,
      companyId,
      kind: 'journal',
      journalSource: generatedFromTemplate
        ? 'generated_from_template'
        : 'one_off',
      isFx,
      reference,
      sequenceMonth: `${yyyy}-${mm}-01`,
      sequenceNumber: reference ? seq - 1 : null,
      date: toYMD(date),
      title,
      description:
        Math.random() < 0.5 ? `Monthly ${title.toLowerCase()}` : null,
      status,
      note:
        Math.random() < 0.25 ? 'Auto-generated by accounting policy.' : null,
      contactId: contact?.id ?? null,
      contactName: contact?.name ?? null,
      currencyId: reportingCurrencyId,
      currencyCode: effectiveCurrencyCode,
      currencyName:
        effectiveCurrencyCode === 'USD' ? 'US Dollar' : effectiveCurrencyCode,
      currencySymbol:
        effectiveCurrencyCode === 'USD' ? '$' : effectiveCurrencyCode,
      exchangeRate,
      ledgerTransactionId: status === 'posted' ? mockId() : null,
      generatedFromTemplateId: generatedFromTemplate,
      generatedAt: generatedFromTemplate ? createdAt.toISOString() : null,
      generatedScheduledForDate: generatedFromTemplate ? toYMD(date) : null,
      autoReversalDate,
      reversalJournalId: null,
      originalJournalId: null,
      reversedAt: null,
      reversalReason: null,
      reversedById: null,
      voidedAt: status === 'voided' ? createdAt.toISOString() : null,
      metadata: null,
      createdAt: createdAt.toISOString(),
      createdById: mockId(),
      updatedAt: createdAt.toISOString(),
      updatedById: null,
      isDeleted: false,
      deletedAt: null,
      totalDebit: totalStr,
      totalCredit: totalStr,
      entriesCount: 0,
    };

    const coa = coaPairs[i % coaPairs.length]!;

    // Sometimes split the debit side across two lines to mimic real entry patterns.
    const splitDebit = Math.random() < 0.28;
    const partA = splitDebit ? Math.round(total * 0.6 * 100) / 100 : total;
    const partB = splitDebit ? Math.round((total - partA) * 100) / 100 : 0;

    const entries: JournalDetailEntry[] = [
      {
        id: mockId(),
        description: `${title} (line 1)`,
        side: 'debit',
        amount: partA,
        coaId: mockId(),
        coaCode: coa.debit.code,
        coaName: coa.debit.name,
        projectId: null,
        projectName: null,
        ledgerEntryId: status === 'posted' ? mockId() : null,
        ledgerEntryFsDate: status === 'posted' ? journalRow.date : null,
        createdAt: createdAt.toISOString(),
        updatedAt: createdAt.toISOString(),
      },
    ];

    if (splitDebit && partB > 0) {
      entries.push({
        id: mockId(),
        description: `${title} (line 2)`,
        side: 'debit',
        amount: partB,
        coaId: mockId(),
        coaCode: coa.debit.code,
        coaName: coa.debit.name,
        projectId: null,
        projectName: null,
        ledgerEntryId: status === 'posted' ? mockId() : null,
        ledgerEntryFsDate: status === 'posted' ? journalRow.date : null,
        createdAt: createdAt.toISOString(),
        updatedAt: createdAt.toISOString(),
      });
    }

    entries.push({
      id: mockId(),
      description: `${title} offset`,
      side: 'credit',
      amount: total,
      coaId: mockId(),
      coaCode: coa.credit.code,
      coaName: coa.credit.name,
      projectId: null,
      projectName: null,
      ledgerEntryId: status === 'posted' ? mockId() : null,
      ledgerEntryFsDate: status === 'posted' ? journalRow.date : null,
      createdAt: createdAt.toISOString(),
      updatedAt: createdAt.toISOString(),
    });

    journalRow.entriesCount = entries.length;

    detailsById.set(id, {
      journal: journalRow,
      entries,
      relatedJournals: {},
    });

    list.push(journalRow);
  }

  // Sort newest first for a natural "recent journals" feel
  list.sort((a, b) => b.date.localeCompare(a.date));

  return { list, detailsById };
}

export function mockCursorResponseFromList(
  journals: JournalListRow[],
): JournalListCursorResponse {
  const statusCounts = {
    draft: journals.filter(
      (journal) => journal.kind === 'journal' && journal.status === 'draft',
    ).length,
    posted: journals.filter(
      (journal) => journal.kind === 'journal' && journal.status === 'posted',
    ).length,
    voided: journals.filter(
      (journal) => journal.kind === 'journal' && journal.status === 'voided',
    ).length,
  };
  const kindCounts = {
    journals: journals.filter((journal) => journal.kind === 'journal').length,
    recurringTemplates: journals.filter(
      (journal) => journal.kind === 'recurring_template',
    ).length,
  };
  const journalSourceCounts = {
    oneOff: journals.filter(
      (journal) =>
        journal.kind === 'journal' && journal.journalSource === 'one_off',
    ).length,
    generatedFromTemplate: journals.filter(
      (journal) =>
        journal.kind === 'journal' &&
        journal.journalSource === 'generated_from_template',
    ).length,
  };
  return {
    rows: journals,
    hasMore: false,
    nextCursor: null,
    facets: {
      allCount: journals.length,
      journalStatusCounts: statusCounts,
      kindCounts,
      journalSourceCounts,
      recurringTemplateStatusCounts: {
        draft: 0,
        active: 0,
        paused: 0,
        closed: 0,
      },
    },
    appliedFilters: {
      dateFrom: null,
      dateTo: null,
      kinds: null,
      journalStatuses: null,
      templateStatuses: null,
      journalSources: null,
    },
  };
}
