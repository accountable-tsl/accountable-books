import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getTimeZones } from '@vvo/tzdb';

import { countryDefaultTimezoneSeeds } from './country-default-timezone-seeds.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(__dirname, '../src/timezone/data.generated.ts');

const timezones = getTimeZones({ includeUtc: true });

const formatOffset = (minutes) => {
  const sign = minutes >= 0 ? '+' : '-';
  const absolute = Math.abs(minutes);
  const hours = String(Math.floor(absolute / 60)).padStart(2, '0');
  const mins = String(absolute % 60).padStart(2, '0');
  return `UTC${sign}${hours}:${mins}`;
};

const unique = (values) => [...new Set(values)];

const formatLabel = (timezone) => {
  const offset = formatOffset(timezone.rawOffsetInMinutes);
  const cities = timezone.mainCities.filter(Boolean).slice(0, 2);
  if (cities.length > 0) {
    return `${offset} ${timezone.alternativeName} - ${cities.join(', ')}`;
  }

  return `${offset} ${timezone.alternativeName} (${timezone.name})`;
};

const formatShortLabel = (timezone) =>
  `${formatOffset(timezone.rawOffsetInMinutes)} ${timezone.alternativeName}`;

const allTimezoneOptions = timezones
  .map((timezone) => ({
    id: timezone.name,
    aliases: unique(
      timezone.group.filter((candidate) => candidate !== timezone.name),
    ).sort(),
    countryCode: timezone.countryCode || undefined,
    countryName: timezone.countryName || undefined,
    label: formatLabel(timezone),
    shortLabel: formatShortLabel(timezone),
    alternativeName: timezone.alternativeName,
    abbreviation: timezone.abbreviation,
    rawOffsetMinutes: timezone.rawOffsetInMinutes,
    mainCities: timezone.mainCities.filter(Boolean).slice(0, 4),
  }))
  .sort((left, right) => {
    if (left.rawOffsetMinutes !== right.rawOffsetMinutes) {
      return left.rawOffsetMinutes - right.rawOffsetMinutes;
    }

    return left.label.localeCompare(right.label);
  });

const canonicalIds = new Set(allTimezoneOptions.map((timezone) => timezone.id));
const timezoneAliasMap = Object.fromEntries(
  allTimezoneOptions.flatMap((timezone) =>
    timezone.aliases.map((alias) => [alias, timezone.id]),
  ),
);

const normalizeTimezoneId = (timezoneId) => {
  if (!timezoneId) return undefined;
  if (canonicalIds.has(timezoneId)) return timezoneId;
  return timezoneAliasMap[timezoneId];
};

const timezoneIdsByCountry = Object.fromEntries(
  Object.entries(
    allTimezoneOptions.reduce((grouped, timezone) => {
      if (!timezone.countryCode) return grouped;

      grouped[timezone.countryCode] ??= [];
      grouped[timezone.countryCode].push(timezone.id);
      return grouped;
    }, {}),
  )
    .map(([countryCode, timezoneIds]) => [
      countryCode,
      timezoneIds.sort((left, right) => {
        const leftTimezone = allTimezoneOptions.find(
          (timezone) => timezone.id === left,
        );
        const rightTimezone = allTimezoneOptions.find(
          (timezone) => timezone.id === right,
        );

        if (!leftTimezone || !rightTimezone) return 0;
        if (leftTimezone.rawOffsetMinutes !== rightTimezone.rawOffsetMinutes) {
          return leftTimezone.rawOffsetMinutes - rightTimezone.rawOffsetMinutes;
        }

        return leftTimezone.label.localeCompare(rightTimezone.label);
      }),
    ])
    .sort(([left], [right]) => left.localeCompare(right)),
);

const countryDefaultTimezoneIds = Object.fromEntries(
  Object.entries(countryDefaultTimezoneSeeds)
    .map(([countryCode, seedTimezoneId]) => {
      const normalized = normalizeTimezoneId(seedTimezoneId);
      const countryTimezoneIds = timezoneIdsByCountry[countryCode] ?? [];

      if (normalized && countryTimezoneIds.includes(normalized)) {
        return [countryCode, normalized];
      }

      if (countryTimezoneIds.length === 1) {
        return [countryCode, countryTimezoneIds[0]];
      }

      if (countryTimezoneIds.length > 1) {
        return [countryCode, countryTimezoneIds[countryTimezoneIds.length - 1]];
      }

      return null;
    })
    .filter(Boolean)
    .sort(([left], [right]) => left.localeCompare(right)),
);

const source = `/**
 * This file is generated by \`packages/utils/scripts/generate-timezones.mjs\`.
 * Do not edit it by hand.
 */

export const allTimezoneOptions = ${JSON.stringify(allTimezoneOptions, null, 2)} as const;

export const timezoneIdsByCountry = ${JSON.stringify(timezoneIdsByCountry, null, 2)} as const;

export const countryDefaultTimezoneIds = ${JSON.stringify(countryDefaultTimezoneIds, null, 2)} as const;

export const timezoneAliasMap = ${JSON.stringify(timezoneAliasMap, null, 2)} as const;
`;

await fs.writeFile(outputPath, source);

console.log(`Generated timezone data at ${outputPath}`);
